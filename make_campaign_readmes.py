HEADER = """# {title}

**Article:** {section}

## Objective

{objective}

## Procedure

{procedure}

## Retained outputs

Per-file SHA-256 values for everything in this campaign are in
`RECORDS_SHA256.txt` at the repository root, keyed by the paths below.

<LIST THE RUN DIRECTORIES HERE, one line each, with a word on what each is>

## Provenance

Each run directory contains `provenance.json` recording the frozen core file
hashes, the Python version, the host, and the effective parameters for that
run. Those hashes can be checked against `CODE_SHA256.txt` at the repository
root.

## What these records support

This campaign supports {supports}. It is not evidence for any other claim in
the article.
"""

WARNING = """
> **These runs are not evidence for any claim in the article.** They are
> retained so that the development record is complete. Do not cite figures
> derived from this directory.
"""


def wrap(text):
    return "\n\n".join(
        textwrap.fill(" ".join(p.split()), 76)
        for p in text.strip().split("\n\n"))


def main():
    written, skipped = [], []
    for name, c in CAMPAIGNS.items():
        if not os.path.isdir(name):
            skipped.append(f"{name} (no such directory)")
            continue
        path = os.path.join(name, "README.md")
        if os.path.exists(path) and not FORCE:
            skipped.append(f"{name} (README exists; --force to overwrite)")
            continue
        body = HEADER.format(title=c["title"], section=c["section"],
                             objective=wrap(c["objective"]),
                             procedure=wrap(c["procedure"]),
                             supports=c["supports"])
        if c.get("warning"):
            body = body.replace("## Objective", WARNING.strip() + "\n\n## Objective")
        with open(path, "w", encoding="utf-8") as f:
            f.write(body)
        written.append(path)

    for p in written:
        print("  wrote", p)
    for s in skipped:
        print("  skipped", s)
    if written:
        print(f"\n{len(written)} written. Fill every <ANGLE BRACKET> before release:")
        print("  grep -rn '<' */README.md")


if __name__ == "__main__":
    main()
