"""
ResearchWesolowskiVDF — Wesolowski VDF over RSA Unknown-Order Group
====================================================================
Reviewer remediation Phase 1.

Group:          Z_N^* where N is an RSA-2048 modulus (unknown order).
                Elements g, y, pi are integers in {1,...,N-1} coprime to N.
Setup:          Single-party trusted RSA setup using OpenSSL via Python's
                `cryptography` library for prime generation. The factors p
                and q exist transiently in process memory; Python's `del`
                does NOT securely erase RAM. A production deployment would
                require a multi-party computation ceremony. Chia's class-
                group VDF (chiavdf) avoids trusted setup entirely and is
                the preferred production alternative.
Proof:          Wesolowski — one group element per proof.
Verification:   Avoids T sequential squarings; polylogarithmic in T,
                using a small number of modular exponentiations.

Dependencies:   Python >=3.10, cryptography (OpenSSL backend).
Licence:        Apache-2.0
"""

import hashlib, struct, time, json, os, csv, statistics, sys
from math import gcd
from typing import Tuple, Dict, List


class VDFError(Exception):
    """Raised for any VDF security or validation failure."""
    pass

# ══════════════════════════════════════════════════════════
#  DETERMINISTIC HASH-TO-PRIME (reviewer item 2)
#  Uses deterministic MR with first 256 primes as bases,
#  plus a Baillie-PSW style strong-probable-prime check.
# ══════════════════════════════════════════════════════════

def _is_prime(n: int) -> bool:
    """
    Primality test delegated to sympy.isprime (SymPy's ntheory module),
    an established implementation of the strong Baillie-PSW test.
    No custom base selection is performed in this codebase.
    """
    from sympy import isprime
    return bool(isprime(n))


def hash_to_prime(data: bytes) -> int:
    """
    Deterministic hash-to-prime for Wesolowski Fiat-Shamir challenge.
    Candidate generation: SHAKE256 (domain-separated), incrementing odd
    candidates. Primality: sympy.isprime (strong Baillie-PSW).
    Fully deterministic — same input always yields the same prime.
    """
    h = hashlib.shake_256(b"WESOLOWSKI_H2P_V1" + data).digest(32)
    candidate = int.from_bytes(h, 'big')
    candidate |= 1
    while not _is_prime(candidate):
        candidate += 2
    return candidate


# ══════════════════════════════════════════════════════════
#  HASH-TO-GROUP (reviewer item 1)
#  SHAKE256 wide-output reduction with negligible modular bias.
#  The extra 16 bytes (128 bits) ensure bias < 2^{-128}.
# ══════════════════════════════════════════════════════════

def hash_to_group(data: bytes, N: int, N_byte_size: int) -> int:
    """
    Map arbitrary bytes to an element of Z_N^*.

    Method: SHAKE256 wide-output reduction with negligible modular bias.
    Expands input to N_byte_size + 16 bytes (256 + 16 = 272 for RSA-2048),
    interprets as big-endian integer, and reduces mod N. The 128 extra bits
    ensure statistical distance from uniform is below 2^{-128}.

    If the result is 0 or shares a factor with N (astronomically unlikely
    for a proper RSA modulus), the function retries with an incremented
    counter until a valid element is found.
    """
    for counter in range(256):
        expanded = hashlib.shake_256(
            b"VDF_H2G_V1" + struct.pack(">B", counter) + data
        ).digest(N_byte_size + 16)
        g = int.from_bytes(expanded, 'big') % N
        if g > 1 and gcd(g, N) == 1:  # reject 0 AND 1 (identity element)
            return g
    raise RuntimeError("hash_to_group: failed to find valid element after 256 attempts")


# ══════════════════════════════════════════════════════════
#  RSA MODULUS SETUP (reviewer items 2, 4, 5, 6, 7)
#  Uses OpenSSL via cryptography library for prime generation.
# ══════════════════════════════════════════════════════════

def generate_rsa_params(bits: int = 2048, output_path: str = "vdf_public_params.json"):
    """
    SETUP UTILITY — run once, separately from normal execution.

    Uses OpenSSL (via Python `cryptography` library) for RSA key generation,
    ensuring primes are generated by a well-audited implementation rather
    than a bespoke primality test (reviewer item 2).

    The factors p and q exist transiently in process memory. Python's `del`
    does NOT securely zero RAM. This is a single-party trusted setup
    suitable for a research prototype only.
    """
    from cryptography.hazmat.primitives.asymmetric import rsa
    from cryptography.hazmat.backends import default_backend

    key = rsa.generate_private_key(
        public_exponent=65537, key_size=bits, backend=default_backend()
    )
    pub = key.public_key().public_numbers()
    N = pub.n

    if N.bit_length() != bits:
        raise VDFError(f"OpenSSL produced {N.bit_length()}-bit modulus, expected {bits}")
    if N % 2 == 0:
        raise VDFError("Generated modulus is even")

    N_byte_size = (N.bit_length() + 7) // 8
    N_bytes = N.to_bytes(N_byte_size, 'big')
    N_hash = hashlib.sha256(b"RSA_MODULUS_V1" + N_bytes).hexdigest()

    # Discard key object containing factors (NOT secure erasure — see docstring)
    del key, pub

    params = {
        'schema_version': 1,
        'group_type': 'RSA',
        'group_definition': 'Z_N^* = {x in {1,...,N-1} : gcd(x,N)=1}',
        'proof_type': 'Wesolowski',
        'modulus_hex': hex(N),
        'modulus_bits': N.bit_length(),
        'modulus_byte_size': N_byte_size,
        'modulus_hash_sha256': N_hash,
        'prime_generation': 'OpenSSL via Python cryptography library',
        'setup_type': 'single_party_trusted',
        'setup_warning': (
            'Factors generated by OpenSSL and held transiently in process memory. '
            'Python del does NOT securely erase RAM. This is a research prototype. '
            'For production: use a multi-party ceremony or class-group VDF (chiavdf).'
        ),
        'domain_separation': {
            'hash_to_group': 'VDF_H2G_V1 (SHAKE256 wide reduction, 128-bit bias bound)',
            'hash_to_prime': 'WESOLOWSKI_H2P_V1 (SHAKE256 + sympy.isprime BPSW)',
            'canonical_input': 'VDF_CANON_INPUT_V1',
        },
    }

    with open(output_path, 'w') as f:
        json.dump(params, f, indent=2)

    print(f"  RSA-{bits} parameters saved to {output_path}")
    print(f"  N.bit_length() = {N.bit_length()} (required: {bits})")
    print(f"  Prime generation: OpenSSL")
    print(f"  N hash: {N_hash[:32]}...")
    return params


# ══════════════════════════════════════════════════════════
#  ResearchWesolowskiVDF (reviewer item 17)
# ══════════════════════════════════════════════════════════

class ResearchWesolowskiVDF:
    """
    Wesolowski VDF over Z_N^* (RSA unknown-order group).
    Research prototype — not production-hardened.
    """
    MODE = "research_wesolowski_rsa"

    def __init__(self, N: int, params_hash: str):
        self.N = N
        self.N_byte_size = (N.bit_length() + 7) // 8
        self.N_bits = N.bit_length()
        self.params_hash = params_hash

    @classmethod
    def from_params(cls, filepath: str) -> 'ResearchWesolowskiVDF':
        """Load and validate parameters. Fails if missing (item 6)."""
        if not os.path.exists(filepath):
            raise FileNotFoundError(
                f"Parameter file not found: {filepath}\n"
                f"Run: python3 production_vdf.py setup"
            )
        with open(filepath) as f:
            params = json.load(f)

        errors = []
        if params.get('schema_version') != 1:
            errors.append(f"schema_version: expected 1, got {params.get('schema_version')}")
        if params.get('group_type') != 'RSA':
            errors.append(f"group_type: expected RSA, got {params.get('group_type')}")
        if params.get('proof_type') != 'Wesolowski':
            errors.append(f"proof_type: expected Wesolowski, got {params.get('proof_type')}")

        N = int(params['modulus_hex'], 16)
        N_byte_size = (N.bit_length() + 7) // 8
        N_bytes = N.to_bytes(N_byte_size, 'big')

        if N.bit_length() != 2048:  # item 7: enforce exactly 2048
            errors.append(f"modulus_bits: expected 2048, got {N.bit_length()}")
        if N % 2 == 0:
            errors.append("Modulus is even — invalid RSA modulus")

        computed_hash = hashlib.sha256(b"RSA_MODULUS_V1" + N_bytes).hexdigest()
        if computed_hash != params.get('modulus_hash_sha256'):
            errors.append("Modulus hash mismatch — file may be corrupted")

        if errors:
            raise ValueError("Parameter validation failed:\n  " + "\n  ".join(errors))

        return cls(N, computed_hash)

    # ── Canonical input (item 9) — single source of truth for T (item 4/5) ──

    def make_canonical_input(self, protocol_version: int, chain_id: bytes,
                             round_number: int, prev_vdf_output: bytes,
                             commitment_root: bytes, difficulty_T: int) -> bytes:
        """Canonical, length-prefixed VDF input encoding."""
        buf = b"VDF_CANON_INPUT_V1"
        buf += struct.pack(">B", protocol_version)
        buf += struct.pack(">H", len(chain_id)) + chain_id
        buf += struct.pack(">I", round_number)
        buf += struct.pack(">H", len(prev_vdf_output)) + prev_vdf_output
        buf += struct.pack(">H", len(commitment_root)) + commitment_root
        buf += struct.pack(">Q", difficulty_T)
        return buf

    @staticmethod
    def extract_T_from_canonical_input(canonical_input: bytes) -> int:
        """Extract difficulty T from canonical input (last 8 bytes)."""
        return struct.unpack(">Q", canonical_input[-8:])[0]

    # ── Element validation (item 10) ──

    def _validate_element(self, elem_bytes: bytes, name: str):
        if len(elem_bytes) != self.N_byte_size:
            raise VDFError(f"{name}: expected {self.N_byte_size} bytes, got {len(elem_bytes)}")
        val = int.from_bytes(elem_bytes, 'big')
        if val <= 1:  # reject 0 AND identity element 1
            raise VDFError(f"{name}: must be > 1")
        if val >= self.N: raise VDFError(f"{name}: >= N")
        if gcd(val, self.N) != 1: raise VDFError(f"{name}: not coprime to N")

    # ── Protocol-level evaluate (item 4: single source of truth for T) ──

    def evaluate_protocol(self, protocol_version: int, chain_id: bytes,
                          round_number: int, prev_vdf_output: bytes,
                          commitment_root: bytes, T: int) -> Tuple[bytes, bytes, bytes, Dict]:
        """
        Protocol-level VDF evaluation. Constructs canonical input internally,
        ensuring T is bound to exactly one source of truth (reviewer item 4).

        Returns: (canonical_input, output_y, proof_pi, metadata)
        """
        canonical_input = self.make_canonical_input(
            protocol_version, chain_id, round_number, prev_vdf_output, commitment_root, T
        )
        y, pi, meta = self._evaluate_raw(canonical_input, T)
        return canonical_input, y, pi, meta

    MAX_T = 10**9  # upper bound on difficulty to prevent resource exhaustion

    def _validate_T(self, T: int):
        """Explicit difficulty validation (raises VDFError, never asserts)."""
        if not isinstance(T, int):
            raise VDFError(f"T must be int, got {type(T).__name__}")
        if T < 1:
            raise VDFError(f"T must be >= 1, got {T}")
        if T > self.MAX_T:
            raise VDFError(f"T exceeds MAX_T ({self.MAX_T}): {T}")

    def _evaluate_raw(self, input_bytes: bytes, T: int) -> Tuple[bytes, bytes, Dict]:
        """Raw evaluate — used by both protocol and benchmark paths."""
        self._validate_T(T)
        g = hash_to_group(input_bytes, self.N, self.N_byte_size)

        t0 = time.perf_counter()
        y = g
        for _ in range(T): y = pow(y, 2, self.N)
        eval_ms = (time.perf_counter() - t0) * 1000

        t1 = time.perf_counter()
        challenge_bytes = (
            g.to_bytes(self.N_byte_size, 'big') +
            y.to_bytes(self.N_byte_size, 'big') +
            struct.pack(">Q", T)
        )
        l = hash_to_prime(challenge_bytes)
        pi = 1; b = 1
        for _ in range(T):
            b = 2 * b
            if b >= l: b -= l; pi = (pi * pi * g) % self.N
            else: pi = (pi * pi) % self.N
        proof_ms = (time.perf_counter() - t1) * 1000

        y_bytes = y.to_bytes(self.N_byte_size, 'big')
        pi_bytes = pi.to_bytes(self.N_byte_size, 'big')

        return y_bytes, pi_bytes, {
            'mode': self.MODE,
            'group': f'Z_N^* (RSA-{self.N_bits})',
            'proof_type': 'Wesolowski',
            'T': T,
            'eval_time_ms': round(eval_ms, 4),
            'proof_gen_time_ms': round(proof_ms, 4),
            'total_prover_time_ms': round(eval_ms + proof_ms, 4),
            'output_bytes': len(y_bytes),
            'proof_bytes': len(pi_bytes),
            'per_step_ns': round(eval_ms * 1e6 / T, 1) if T > 0 else 0,
        }

    # ── Protocol-level verify (item 4: reconstructs input from witness fields) ──

    def verify_protocol(self, protocol_version: int, chain_id: bytes,
                        round_number: int, prev_vdf_output: bytes,
                        commitment_root: bytes, T: int,
                        y_bytes: bytes, pi_bytes: bytes) -> Tuple[bool, float]:
        """
        Protocol-level verification. Reconstructs canonical input from
        authenticated witness fields — single source of truth for T (item 4).
        """
        canonical_input = self.make_canonical_input(
            protocol_version, chain_id, round_number, prev_vdf_output, commitment_root, T
        )
        return self._verify_raw(canonical_input, T, y_bytes, pi_bytes)

    def _verify_raw(self, input_bytes: bytes, T: int,
                    y_bytes: bytes, pi_bytes: bytes) -> Tuple[bool, float]:
        """Raw verify — used by both protocol and benchmark paths."""
        t0 = time.perf_counter()
        try:
            self._validate_T(T)
            self._validate_element(y_bytes, "y")
            self._validate_element(pi_bytes, "pi")
        except (ValueError, VDFError):
            return False, round((time.perf_counter() - t0) * 1000, 4)

        g = hash_to_group(input_bytes, self.N, self.N_byte_size)
        y = int.from_bytes(y_bytes, 'big')
        pi = int.from_bytes(pi_bytes, 'big')

        challenge_bytes = (
            g.to_bytes(self.N_byte_size, 'big') +
            y_bytes +
            struct.pack(">Q", T)
        )
        l = hash_to_prime(challenge_bytes)
        r = pow(2, T, l)
        lhs = (pow(g, r, self.N) * pow(pi, l, self.N)) % self.N
        return (lhs == y), round((time.perf_counter() - t0) * 1000, 4)


