def run_benchmark(vdf, T_values=None, trials=30, out_dir="results/vdf"):
    """Benchmark with >=30 trials (item 9), proper percentiles (item 10)."""
    if T_values is None:
        T_values = [100, 500, 1000, 2000, 5000, 10000]

    print(f"\n{'='*72}")
    print(f"  BENCHMARK — {vdf.MODE} (RSA-{vdf.N_bits})")
    print(f"  Trials per T: {trials}")
    print(f"{'='*72}\n")

    os.makedirs(out_dir, exist_ok=True)
    raw_rows = []

    hdr = f"  {'T':>8} {'Eval':>9} {'Proof':>9} {'Total':>9} {'Verify':>9} {'Out':>5} {'Prf':>5}"
    print(hdr)
    print(f"  {'-'*8} {'-'*9} {'-'*9} {'-'*9} {'-'*9} {'-'*5} {'-'*5}")

    summary_rows = []
    for T in T_values:
        evals, proofs, verifs = [], [], []
        for trial in range(trials):
            inp = f"BENCH:T={T}:trial={trial}:seed=42".encode()
            y, pi, meta = vdf._evaluate_raw(inp, T)
            valid, v_ms = vdf._verify_raw(inp, T, y, pi)
            assert valid, f"FAIL T={T} trial={trial}"
            evals.append(meta['eval_time_ms'])
            proofs.append(meta['proof_gen_time_ms'])
            verifs.append(v_ms)
            raw_rows.append({
                'T': T, 'trial': trial,
                'eval_ms': meta['eval_time_ms'],
                'proof_ms': meta['proof_gen_time_ms'],
                'verify_ms': v_ms,
                'output_bytes': meta['output_bytes'],
                'proof_bytes': meta['proof_bytes'],
            })

        me = statistics.mean(evals)
        mp = statistics.mean(proofs)
        mv = statistics.mean(verifs)
        print(f"  {T:>8,} {me:>9.2f} {mp:>9.2f} {me+mp:>9.2f} {mv:>9.2f} {meta['output_bytes']:>5} {meta['proof_bytes']:>5}")

        se = sorted(evals); sp = sorted(proofs); sv = sorted(verifs)
        p95_idx = min(int(len(sv)*0.95), len(sv)-1)  # item 10: proper index

        summary_rows.append({
            'T': T, 'trials': trials,
            'eval_ms_mean': round(me, 4),
            'eval_ms_median': round(statistics.median(evals), 4),
            'eval_ms_std': round(statistics.stdev(evals), 4) if trials > 1 else 0,
            'eval_ms_p95': round(se[p95_idx], 4),
            'proof_ms_mean': round(mp, 4),
            'proof_ms_median': round(statistics.median(proofs), 4),
            'proof_ms_std': round(statistics.stdev(proofs), 4) if trials > 1 else 0,
            'verify_ms_mean': round(mv, 4),
            'verify_ms_median': round(statistics.median(verifs), 4),
            'verify_ms_std': round(statistics.stdev(verifs), 4) if trials > 1 else 0,
            'verify_ms_p95': round(sv[p95_idx], 4),
            'output_bytes': meta['output_bytes'],
            'proof_bytes': meta['proof_bytes'],
            'per_step_ns': round(me * 1e6 / T, 1),
        })

    if len(T_values) >= 2:
        ratio = summary_rows[-1]['eval_ms_mean'] / summary_rows[0]['eval_ms_mean']
        expected = T_values[-1] / T_values[0]
        print(f"\n  Scaling: {T_values[-1]:,}/{T_values[0]:,} = {ratio:.2f}x (expected {expected:.1f}x)")

    with open(f"{out_dir}/vdf_benchmark_raw.csv", 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=raw_rows[0].keys()); w.writeheader(); w.writerows(raw_rows)
    with open(f"{out_dir}/vdf_benchmark_summary.csv", 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=summary_rows[0].keys()); w.writeheader(); w.writerows(summary_rows)

    print(f"\n  Raw: {out_dir}/vdf_benchmark_raw.csv ({len(raw_rows)} rows)")
    print(f"  Summary: {out_dir}/vdf_benchmark_summary.csv ({len(summary_rows)} rows)")
    return summary_rows


