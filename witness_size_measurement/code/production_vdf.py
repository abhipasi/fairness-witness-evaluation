def save_test_vectors(vdf, out_dir="results/vdf"):
    """Deterministic test vectors — no timing metadata (item 8)."""
    os.makedirs(out_dir, exist_ok=True)

    T = 500
    canon = vdf.make_canonical_input(1, b"TEST_VECTOR_CHAIN", 1, b'\xaa'*32, b'\xbb'*32, T)
    g = hash_to_group(canon, vdf.N, vdf.N_byte_size)
    y, pi, _ = vdf._evaluate_raw(canon, T)

    challenge_bytes = g.to_bytes(vdf.N_byte_size,'big') + y + struct.pack(">Q", T)
    l = hash_to_prime(challenge_bytes)
    r = pow(2, T, l)

    vectors = {
        'params_hash': vdf.params_hash,
        'modulus_bits': vdf.N_bits,
        'canonical_input_hex': canon.hex(),
        'T': T,
        'g_hex': hex(g),
        'challenge_prime_l_hex': hex(l),
        'remainder_r_hex': hex(r),
        'output_y_hex': y.hex(),
        'proof_pi_hex': pi.hex(),
        'output_bytes': len(y),
        'proof_bytes': len(pi),
        # NO timing data — item 8
    }

    path = f"{out_dir}/vdf_test_vectors.json"
    with open(path, 'w') as f:
        json.dump(vectors, f, indent=2)
    print(f"  Test vectors (deterministic): {path}")


