def run_all_tests(vdf: ResearchWesolowskiVDF):
    print(f"\n{'='*72}")
    print(f"  VALIDATION TESTS")
    print(f"{'='*72}\n")

    T = 1000
    chain = b"TEST_CHAIN_V1"
    rnd = 42
    prev = hashlib.sha256(b"prev").digest()
    comm = hashlib.sha256(b"comm").digest()
    N_bs = vdf.N_byte_size

    canon, y, pi, _ = vdf.evaluate_protocol(1, chain, rnd, prev, comm, T)

    # Different round (item 12: tests round, not T)
    diff_round_canon, _, _, _ = vdf.evaluate_protocol(1, chain, 99, prev, comm, T)

    tests = [
        # Correct
        ("Correct verification",              canon, T, y, pi, True),
        # Tampered elements
        ("Tampered output (1 bit)",           canon, T, bytes([y[0]^1])+y[1:], pi, False),
        ("Tampered proof (1 bit)",            canon, T, y, bytes([pi[0]^1])+pi[1:], False),
        ("Wrong input bytes",                 b"WRONG", T, y, pi, False),
        ("Wrong difficulty T-1",              canon, T-1, y, pi, False),
        ("Wrong difficulty T+1",              canon, T+1, y, pi, False),
        # Item 12: actual round change
        ("Wrong round (42 vs 99)",            diff_round_canon, T, y, pi, False),
        # Item 11: protocol field tampering
        ("Wrong chain ID",                    vdf.make_canonical_input(1,b"WRONG",rnd,prev,comm,T), T, y, pi, False),
        ("Wrong protocol version",            vdf.make_canonical_input(9,chain,rnd,prev,comm,T), T, y, pi, False),
        ("Modified prev VDF output",          vdf.make_canonical_input(1,chain,rnd,b'\xff'*32,comm,T), T, y, pi, False),
        ("Modified commitment root",          vdf.make_canonical_input(1,chain,rnd,prev,b'\xff'*32,T), T, y, pi, False),
        ("Modified T in canonical input",     vdf.make_canonical_input(1,chain,rnd,prev,comm,9999), T, y, pi, False),
        # Item 10: malformed elements
        ("Truncated output",                  canon, T, y[:N_bs//2], pi, False),
        ("Truncated proof",                   canon, T, y, pi[:N_bs//2], False),
        ("Zero output",                       canon, T, b'\x00'*N_bs, pi, False),
        ("Zero proof",                        canon, T, y, b'\x00'*N_bs, False),
        ("Oversized output (+1)",             canon, T, y+b'\x00', pi, False),
        ("Oversized proof (+1)",              canon, T, y, pi+b'\x00', False),
        ("Output = N",                        canon, T, vdf.N.to_bytes(N_bs,'big'), pi, False),
    ]

    passed = failed = 0
    for name, inp, t, yt, pt, expected in tests:
        valid, _ = vdf._verify_raw(inp, t, yt, pt)
        ok = (valid == expected)
        status = "PASS" if ok else "FAIL"
        if ok: passed += 1
        else: failed += 1
        print(f"  {status}: {name:<42} valid={valid} (expected {expected})")

    # Item 5: wrong public parameters test
    print(f"\n  Wrong-parameter tests:")
    vdf2 = _make_small_test_vdf()
    if vdf2:
        valid2, _ = vdf2._verify_raw(canon, T, y, pi)
        ok = not valid2
        status = "PASS" if ok else "FAIL"
        if ok: passed += 1
        else: failed += 1
        print(f"  {status}: {'Proof from VDF-A verified on VDF-B':<42} valid={valid2} (expected False)")
    else:
        print(f"  SKIP: Could not create second parameter set")

    # Parameter-validation tests (one mutation each, expect ValueError/VDFError only)
    print(f"\n  Parameter-validation tests:")
    import tempfile, copy

    # Baseline valid params (from the loaded VDF's own file structure)
    with open("vdf_public_params.json") as _f:
        base_params = json.load(_f)

    def _mutate_and_expect_rejection(name, mutation):
        """Write mutated params, expect from_params to raise ValueError or VDFError ONLY."""
        nonlocal passed, failed
        params = copy.deepcopy(base_params)
        mutation(params)
        with tempfile.NamedTemporaryFile(mode='w', suffix='.json', delete=False) as tf:
            json.dump(params, tf); tf.flush()
            path = tf.name
        try:
            ResearchWesolowskiVDF.from_params(path)
            print(f"  FAIL: {name:<42} (accepted invalid params)")
            failed += 1
        except (ValueError, VDFError):
            print(f"  PASS: {name:<42} (correctly rejected)")
            passed += 1
        except Exception as e:
            print(f"  FAIL: {name:<42} (unexpected {type(e).__name__}: {e})")
            failed += 1
        finally:
            os.unlink(path)

    def _set(key, value):
        def m(p): p[key] = value
        return m

    _mutate_and_expect_rejection("Wrong schema_version only", _set('schema_version', 99))
    _mutate_and_expect_rejection("Wrong group_type only", _set('group_type', 'ClassGroup'))
    _mutate_and_expect_rejection("Wrong proof_type only", _set('proof_type', 'Pietrzak'))
    _mutate_and_expect_rejection("Corrupted modulus hash only", _set('modulus_hash_sha256', 'deadbeef'*8))
    def _set_modulus_with_valid_hash(new_N):
        """Mutate modulus AND recompute its hash — so ONLY size/parity is wrong."""
        def m(p):
            nb = (new_N.bit_length() + 7) // 8
            p['modulus_hex'] = hex(new_N)
            p['modulus_bits'] = new_N.bit_length()
            p['modulus_byte_size'] = nb
            p['modulus_hash_sha256'] = hashlib.sha256(
                b"RSA_MODULUS_V1" + new_N.to_bytes(nb, 'big')).hexdigest()
        return m

    _mutate_and_expect_rejection("1024-bit modulus (hash valid)",
        _set_modulus_with_valid_hash((1<<1023) | (1<<100) | 1))
    _mutate_and_expect_rejection("Even modulus (hash valid)",
        _set_modulus_with_valid_hash(int(base_params['modulus_hex'],16) - 1))

    # Corrupted JSON file (parse error is also acceptable rejection)
    with tempfile.NamedTemporaryFile(mode='w', suffix='.json', delete=False) as tf:
        tf.write('{"schema_version": 1, CORRUPT'); tf.flush(); cpath = tf.name
    try:
        ResearchWesolowskiVDF.from_params(cpath)
        print(f"  FAIL: {'Corrupted parameter JSON':<42} (accepted)")
        failed += 1
    except (ValueError, VDFError, json.JSONDecodeError):
        print(f"  PASS: {'Corrupted parameter JSON':<42} (correctly rejected)")
        passed += 1
    finally:
        os.unlink(cpath)

    print(f"\n  Total: {passed} passed, {failed} failed")
    assert failed == 0, f"{failed} tests FAILED"
    return passed

def _make_small_test_vdf():
    """Create a second VDF with different parameters for cross-parameter test."""
    try:
        from cryptography.hazmat.primitives.asymmetric import rsa
        from cryptography.hazmat.backends import default_backend
        key = rsa.generate_private_key(65537, 2048, default_backend())
        N2 = key.public_key().public_numbers().n
        N2_bytes = N2.to_bytes(256, 'big')
        h2 = hashlib.sha256(b"RSA_MODULUS_V1" + N2_bytes).hexdigest()
        return ResearchWesolowskiVDF(N2, h2)
    except Exception:
        return None


