def run_consensus_integration_test(vdf):
    """
    Verify the protocol-level API works end-to-end.
    This tests evaluate_protocol → verify_protocol, the actual API
    that the consensus code must call (item 19).
    """
    print(f"\n{'='*72}")
    print(f"  CONSENSUS INTEGRATION TEST")
    print(f"{'='*72}\n")

    chain_id = b"FAIRNESS_WITNESS_V1"
    round_number = 7
    prev_vdf_output = hashlib.sha256(b"genesis_seed").digest()
    commitment_root = hashlib.sha256(b"merkle_root_round_7").digest()
    T = 1000

    # Step 1-2: evaluate_protocol constructs canonical input + evaluates
    canon, y, pi, meta = vdf.evaluate_protocol(
        1, chain_id, round_number, prev_vdf_output, commitment_root, T
    )
    print(f"  evaluate_protocol: {meta['eval_time_ms']:.2f}ms eval + {meta['proof_gen_time_ms']:.2f}ms proof")
    print(f"  Output: {len(y)} bytes | Proof: {len(pi)} bytes")

    # Step 3: verify_protocol reconstructs input from same fields
    valid, v_ms = vdf.verify_protocol(
        1, chain_id, round_number, prev_vdf_output, commitment_root, T, y, pi
    )
    print(f"  verify_protocol: valid={valid}, {v_ms:.2f}ms")

    # Step 4: T consistency — cannot evaluate with wrong T
    canon_wrong_T, y2, pi2, _ = vdf.evaluate_protocol(
        1, chain_id, round_number, prev_vdf_output, commitment_root, 500
    )
    cross_valid, _ = vdf.verify_protocol(
        1, chain_id, round_number, prev_vdf_output, commitment_root, T, y2, pi2
    )
    print(f"  T-consistency: eval(T=500) verify(T=1000) → valid={cross_valid} (expected False)")

    # Step 5: leader derivation from VDF output
    leader_hash = hashlib.sha256(
        b"LEADER_V1" + y + commitment_root + struct.pack(">I", round_number)
    ).digest()
    total_stake = 48000
    u = int.from_bytes(leader_hash, 'big') % total_stake
    print(f"  Leader selection: u={u} / {total_stake}")

    assert valid, "Protocol verification failed"
    assert not cross_valid, "T-consistency check failed"
    print(f"\n  CONSENSUS INTEGRATION: PASSED")
    return True


